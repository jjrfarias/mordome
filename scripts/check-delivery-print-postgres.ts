import { queueSaleReceipts } from "../lib/receipt-print-jobs.ts";
import assert from 'node:assert/strict';
import { randomUUID, randomBytes, createHash } from 'node:crypto';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '../generated/prisma/client.ts';
const url = process.env.TEST_DATABASE_URL!, base = process.env.TEST_APP_URL!;
if (!url || !base || ![url, base].every(v => ['localhost', '127.0.0.1'].includes(new URL(v).hostname)) || !new URL(url).pathname.endsWith('_test')) throw Error('Isolated local test required');
const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: url }) });
const stamp = randomUUID(), token = randomBytes(32).toString('hex'), agentToken = randomBytes(32).toString('hex');
const hash = (v: string) => createHash('sha256').update(v).digest('hex');
const org = await db.organization.create({ data: { name: 'Delivery Print QA', slug: stamp } });
const user = await db.user.create({ data: { username: stamp, name: 'QA', passwordHash: 'disabled' } });
const call = async (path: string, body: object, auth = true, agent = false) => {
  const r = await fetch(base + path, { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json', ...(auth ? agent ? { Authorization: `Bearer ${agentToken}` } : { Cookie: `mordome_session=${token}` } : {}) }, body: JSON.stringify(body) });
  return { status: r.status, data: await r.json() };
};
try {
  const unit = await db.establishment.create({ data: { organizationId: org.id, name: 'QA', slug: stamp } });
  const permissions = await Promise.all(['delivery.operate', 'print.reprint'].map(key => db.permission.upsert({ where: { key }, update: {}, create: { key, module: key.split('.')[0], description: 'QA' } })));
  const role = await db.customRole.create({ data: { organizationId: org.id, name: 'QA', permissions: { create: permissions.map(p => ({ permissionId: p.id })) } } });
  await db.organizationMembership.create({ data: { organizationId: org.id, userId: user.id, status: 'ACTIVE', accesses: { create: { establishmentId: unit.id } }, roles: { create: { roleId: role.id } } } });
  await db.session.create({ data: { userId: user.id, tokenHash: hash(token), activeEstablishmentId: unit.id, expiresAt: new Date(Date.now() + 3600000) } });
  const order = await db.deliveryOrder.create({ data: { establishmentId: unit.id, customerName: 'Cliente QA', customerPhone: '22999999999', address: 'Rua QA, 1', deliveryFee: 5, status: 'PREPARING', items: { create: { productName: 'Pastel QA', quantity: 2, unitPrice: 20 } } } });
  const agent = await db.kitchenPrintAgent.create({ data: { establishmentId: unit.id, name: 'QA', tokenHash: hash(agentToken), receiptsActivatedAt: new Date() } });
  const endpoint = '/api/operations/delivery/print';
  const conference = { orderId: order.id, mode: 'CONFERENCE', discount: 2 };
  assert.equal((await call(endpoint, conference, false)).status, 401);
  assert.equal((await call(endpoint, { ...conference, orderId: 'foreign' })).status, 404);
  assert.equal((await call(endpoint, { ...conference, discount: 999 })).status, 409);
  assert.equal((await call(endpoint, { orderId: order.id, mode: 'RECEIPT' })).status, 409);
  const result = await call(endpoint, conference);
  assert.equal(result.status, 200, JSON.stringify(result)); assert.equal(result.data.queued, true); assert.equal(result.data.receipt.total, 43);
  const job = await db.kitchenPrintJob.findFirstOrThrow({ where: { agentId: agent.id } });
  assert.equal(job.conferenceDeliveryOrderId, order.id); assert.equal(job.saleId, null); assert.equal(job.orderId, null);
  assert.equal(await db.sale.count({ where: { establishmentId: unit.id } }), 0);
  assert.equal((await db.deliveryOrder.findUniqueOrThrow({ where: { id: order.id } })).status, 'PREPARING');
  const worker = '/api/integrations/kitchen-print';
  assert.equal((await call(worker, { jobId: job.id, action: 'CLAIM' }, true, true)).status, 200);
  assert.equal((await call(worker, { jobId: job.id, action: 'ACK' }, true, true)).status, 200);
  await call(endpoint, conference);
  const pending = await db.kitchenPrintJob.findFirstOrThrow({ where: { agentId: agent.id, status: 'PENDING' } });
  const sale = await db.sale.create({ data: { organizationId: org.id, establishmentId: unit.id, operatorId: user.id, idempotencyKey: randomUUID(), channel: 'DELIVERY', subtotal: 40, deliveryFee: 5, discount: 3, total: 42, items: { create: { productName: 'Pastel QA', quantity: 2, unitPrice: 20, total: 40 } }, payments: { create: { method: 'CASH', amount: 42, receivedAmount: 50, changeAmount: 8 } } } });
  await db.deliveryOrder.update({ where: { id: order.id }, data: { status: 'DELIVERED', saleId: sale.id } });
  assert.equal((await call(endpoint, conference)).status, 409);
  assert.equal((await call(worker, { jobId: pending.id, action: 'CLAIM' }, true, true)).status, 409);
  const receipt = { orderId: order.id, mode: 'RECEIPT' };
  const [scans] = await Promise.all([Promise.all(Array.from({ length: 4 }, () => call(endpoint, receipt))), queueSaleReceipts(db, { ...agent, establishment: { name: 'QA' } })]);
  assert.ok(scans.every(r => r.status === 200 && r.data.receipt.total === 42), JSON.stringify(scans));
  assert.equal(await db.kitchenPrintJob.count({ where: { saleId: sale.id } }), 1);
  const paidJob = await db.kitchenPrintJob.findFirstOrThrow({ where: { saleId: sale.id } });
  assert.match(Buffer.from(paidJob.payload, 'base64').toString('ascii'), /Troco\s+R\$ 8,00/);
  assert.equal((await call(worker, { jobId: paidJob.id, action: 'CLAIM' }, true, true)).status, 200);
  await call(worker, { jobId: paidJob.id, action: 'ACK' }, true, true);
  await call(endpoint, receipt);
  assert.equal((await db.kitchenPrintJob.findUniqueOrThrow({ where: { id: paidJob.id } })).status, 'SENT');
  assert.equal((await call(endpoint, { ...receipt, reprint: true })).status, 200);
  assert.equal((await db.kitchenPrintJob.findUniqueOrThrow({ where: { id: paidJob.id } })).status, 'PENDING');
  assert.equal(await db.auditEvent.count({ where: { entityId: sale.id, action: 'PRINT_REPRINT' } }), 1);
  await db.sale.update({ where: { id: sale.id }, data: { status: 'CANCELLED' } });
  assert.equal((await call(endpoint, receipt)).status, 409);
  assert.equal((await call(worker, { jobId: paidJob.id, action: 'CLAIM' }, true, true)).status, 409);
  console.log('PASS: delivery conference, queue CLAIM/ACK, unchanged open order, persisted payment/troco, concurrent receipt deduplication, audited reprint, cancelled sale blocked');
} finally {
  await db.kitchenPrintAgent.deleteMany({ where: { establishment: { organizationId: org.id } } });
  await db.auditEvent.deleteMany({ where: { organizationId: org.id } });
  await db.deliveryOrder.deleteMany({ where: { establishment: { organizationId: org.id } } });
  await db.sale.deleteMany({ where: { organizationId: org.id } });
  await db.session.deleteMany({ where: { userId: user.id } });
  await db.establishmentAccess.deleteMany({ where: { establishment: { organizationId: org.id } } });
  await db.organizationMembership.deleteMany({ where: { organizationId: org.id } });
  await db.customRole.deleteMany({ where: { organizationId: org.id } });
  await db.establishment.deleteMany({ where: { organizationId: org.id } });
  await db.organization.delete({ where: { id: org.id } });
  await db.user.delete({ where: { id: user.id } });
  await db.$disconnect();
}

